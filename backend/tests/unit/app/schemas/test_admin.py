"""The administrator's screens: what they may ask for and what they are told.

Two things here are worth asserting beyond the shapes. A moderator is created by address
alone — the password is generated by the platform, because one a person invents while creating
the sixth moderator this month is one weak password or one password used six times (ADR 28).

And a category slug is lowercased before the pattern sees it. `StringConstraints(to_lower=...)`
would lowercase after, so `PETS` would be refused rather than accepted as `pets` — the same
trap the subdomain hit, and the reason both normalise with a `BeforeValidator`.
"""

import uuid
from datetime import UTC, date, datetime

import pytest
from pydantic import ValidationError

from app.models import AuditLog, Category, CategoryStatus, User, UserRole
from app.models.category import CATEGORY_SLUG_MAX_LENGTH
from app.schemas.admin import (
    ActivityRead,
    AdminCategoryRead,
    AuditLogRead,
    CategoryCreateRequest,
    CategoryUpdateRequest,
    HandedOverRead,
    ModeratorCreateRequest,
    RoleChangeRequest,
    SystemStateRead,
)
from app.services.system_health import DayOfActivity, Occupancy, Resources


def test_a_moderator_is_created_by_address_and_nothing_else() -> None:
    """The password comes back in the answer, once; it is never asked for here."""
    assert set(ModeratorCreateRequest.model_fields) == {"email"}
    assert (
        ModeratorCreateRequest(email="Moderator@Allstore.AM").normalized_email
        == "moderator@allstore.am"
    )


def test_a_password_offered_on_the_creation_form_is_refused() -> None:
    """`extra="forbid"`: silently dropping it would let a client believe it chose one."""
    body: dict[str, object] = {"email": "moderator@allstore.am", "password": "qwerty"}

    with pytest.raises(ValidationError):
        ModeratorCreateRequest(**body)


def test_the_handed_over_password_is_answered_once_and_belongs_to_an_account() -> None:
    """The only place this password is ever readable: the row holds a hash, the journal
    records that it happened rather than what was handed over, and no letter carries it."""
    assert set(HandedOverRead.model_fields) == {"user", "password"}


@pytest.mark.parametrize("role", list(UserRole))
def test_every_role_the_platform_has_can_be_asked_for(role: UserRole) -> None:
    assert RoleChangeRequest(role=role).role is role


def test_a_role_nobody_defined_is_refused() -> None:
    with pytest.raises(ValidationError):
        RoleChangeRequest(role="superuser")


@pytest.mark.parametrize(
    ("typed", "stored"), [("pets", "pets"), ("PETS", "pets"), (" Pets ", "pets")]
)
def test_a_slug_is_lowercased_before_the_pattern_sees_it(typed: str, stored: str) -> None:
    assert CategoryCreateRequest(name="Питомцы", slug=typed).slug == stored


@pytest.mark.parametrize(
    "slug",
    [
        "",
        "-pets",  # a slug may not begin with a separator
        "pets-",  # nor end with one
        "pets--toys",  # nor double one
        "pets toys",  # a space is not a separator
        "питомцы",  # not an ascii slug
        "p" * (CATEGORY_SLUG_MAX_LENGTH + 1),
    ],
)
def test_a_slug_nobody_could_put_in_an_address_is_refused(slug: str) -> None:
    with pytest.raises(ValidationError):
        CategoryCreateRequest(name="Питомцы", slug=slug)


def test_a_category_with_no_parent_is_a_top_level_one() -> None:
    assert CategoryCreateRequest(name="Питомцы", slug="pets").parent_id is None


def test_a_category_can_be_renamed_and_hidden_but_not_readdressed() -> None:
    """The slug is the address a visitor filters by and a link they may have saved, so
    renaming it is not an edit — it is breaking somebody's bookmark."""
    assert set(CategoryUpdateRequest.model_fields) == {"name", "status"}

    body: dict[str, object] = {"slug": "pets"}
    with pytest.raises(ValidationError):
        CategoryUpdateRequest(**body)


def test_an_administrators_tree_carries_what_a_visitor_must_not_see() -> None:
    """The public tree does not have a status at all: an administrator manages what is hidden
    just as much as what is shown."""
    root = Category(id=uuid.uuid4(), slug="pets", name="Питомцы", status=CategoryStatus.ACTIVE)
    root.children = [
        Category(id=uuid.uuid4(), slug="toys", name="Игрушки", status=CategoryStatus.HIDDEN)
    ]

    tree = AdminCategoryRead.from_root(root)

    assert tree.status is CategoryStatus.ACTIVE
    assert [child.status for child in tree.children] == [CategoryStatus.HIDDEN]


def test_a_journal_names_people_by_their_address() -> None:
    """A journal is read by people, and a page of identifiers is a page nobody can read."""
    entry = AuditLog(
        id=uuid.uuid4(),
        action="role_granted",
        entity_type="user",
        entity_id=uuid.uuid4(),
        details={"role": "moderator"},
        created_at=datetime.now(UTC),
    )
    entry.actor = User(id=uuid.uuid4(), email="admin@allstore.am")

    read = AuditLogRead.from_entry(entry)

    assert read.actor_email == "admin@allstore.am"
    assert read.details == {"role": "moderator"}


def test_what_the_platform_did_by_itself_has_no_author() -> None:
    """A deletion run by the worker is still worth recording, and inventing an actor for it
    would be worse than saying there was none."""
    entry = AuditLog(
        id=uuid.uuid4(),
        action="session_expired",
        entity_type="session",
        entity_id=None,
        details={},
        created_at=datetime.now(UTC),
    )
    entry.actor = None

    assert AuditLogRead.from_entry(entry).actor_email is None


def test_the_state_of_the_machine_is_one_shape_made_of_two_readings() -> None:
    """Nothing is stored, so nothing can be stale — and the two halves come from two places."""
    resources = Resources(
        cpu_percent=4.5,
        memory_percent=31.0,
        memory_total_mb=16000,
        memory_used_mb=5000,
        disk_percent=42.0,
        disk_total_gb=500,
        disk_free_gb=290,
        uptime_seconds=86400,
    )
    occupancy = Occupancy(
        users=12,
        sellers=3,
        products=40,
        businesses_pending=1,
        reports_open=2,
        live_sessions=5,
        database_size_mb=64,
    )

    state = SystemStateRead.of(resources, occupancy)

    assert state.cpu_percent == 4.5
    assert state.users == 12
    assert state.database_size_mb == 64


def test_a_quiet_day_is_a_zero_rather_than_a_hole() -> None:
    """A missing day would read as a day nobody collected, which is a different worry."""
    series = ActivityRead.of(
        [
            DayOfActivity(day=date(2026, 11, 12), registrations=0, logins=0, products=0, reports=0),
            DayOfActivity(day=date(2026, 11, 13), registrations=2, logins=9, products=1, reports=0),
        ]
    )

    assert [day.day for day in series.days] == [date(2026, 11, 12), date(2026, 11, 13)]
    assert series.days[0].registrations == 0
